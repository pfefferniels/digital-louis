#!/usr/bin/env python3
"""
Extract the SMuFL glyphs the renderer uses from the Leipzig font as it is
distributed with Verovio, and write them as a typed TypeScript module.

Outlines stay in font units (1000 per em, y up); bounding boxes and anchors
are converted to staff spaces (250 font units), y up, as SMuFL defines them.

usage: extract_glyphs.py VEROVIO_CHECKOUT [--out src/renderer/leipzig.ts]
"""
import argparse
import json
import xml.etree.ElementTree as ET
from pathlib import Path

UNITS_PER_STAFF_SPACE = 250

# SMuFL name -> codepoint, in the order the module lists them
GLYPHS = {
    'noteheadDoubleWholeSquare': 'E0A1',
    'noteheadWhole': 'E0A2',
    'noteheadHalf': 'E0A3',
    'noteheadBlack': 'E0A4',
    'gClef': 'E050',
    'cClef': 'E05C',
    'fClef': 'E062',
    'flag8thUp': 'E240',
    'flag8thDown': 'E241',
    'accidentalFlat': 'E260',
    'accidentalNatural': 'E261',
    'accidentalSharp': 'E262',
    'restWhole': 'E4E3',
    'restHalf': 'E4E4',
    'restQuarter': 'E4E5',
    'rest8th': 'E4E6',
    'ornamentTrill': 'E566',
    'ornamentShortTrill': 'E56C',
    'ornamentMordent': 'E56D',
}

ENGRAVING_DEFAULTS = (
    'staffLineThickness', 'stemThickness', 'beamThickness', 'legerLineThickness',
    'legerLineExtension', 'thinBarlineThickness', 'thickBarlineThickness',
    'barlineSeparation', 'tieMidpointThickness', 'tieEndpointThickness',
)


def staff_spaces(value):
    return round(float(value) / UNITS_PER_STAFF_SPACE, 4)


def outline(glyph_file):
    path = ET.parse(glyph_file).getroot().find('path')
    if path is None or path.get('transform') != 'scale(1,-1)':
        raise ValueError(f'{glyph_file}: expected a single path in font orientation')
    return path.get('d')


def metrics(bounding_boxes, codepoint):
    entry = bounding_boxes.find(f"g[@c='{codepoint}']")
    if entry is None:
        raise ValueError(f'no metrics for {codepoint}')
    bbox = {
        'x': staff_spaces(entry.get('x')), 'y': staff_spaces(entry.get('y')),
        'width': staff_spaces(entry.get('w')), 'height': staff_spaces(entry.get('h')),
    }
    anchors = {a.get('n'): {'x': float(a.get('x')), 'y': float(a.get('y'))} for a in entry.findall('a')}
    return bbox, anchors


def ts_number(value):
    return f'{value:g}'


def ts_object(fields):
    return '{ ' + ', '.join(f'{key}: {ts_number(value)}' for key, value in fields.items()) + ' }'


def module(verovio):
    data = verovio / 'data'
    bounding_boxes = ET.parse(data / 'Leipzig.xml').getroot()
    defaults = json.loads((verovio / 'fonts' / 'Leipzig' / 'leipzig_metadata.json').read_text())['engravingDefaults']

    entries = []
    for name, codepoint in GLYPHS.items():
        bbox, anchors = metrics(bounding_boxes, codepoint)
        anchor_text = ', '.join(f'{n}: {ts_object(p)}' for n, p in sorted(anchors.items()))
        anchor_object = f'{{ {anchor_text} }}' if anchors else '{}'
        entries.append(
            f"    {name}: {{\n"
            f"        codepoint: '{codepoint}',\n"
            f"        bbox: {ts_object(bbox)},\n"
            f"        anchors: {anchor_object},\n"
            f"        outline: '{outline(data / 'Leipzig' / f'{codepoint}.xml')}',\n"
            f"    }},"
        )
    engraving = '\n'.join(f'    {key}: {defaults[key]},' for key in ENGRAVING_DEFAULTS)

    return f"""/**
 * Generated by tools/renderer/extract_glyphs.py - do not edit.
 *
 * Glyphs of the Leipzig font (https://github.com/rism-digital/leipzig,
 * SIL Open Font License 1.1) as distributed with Verovio. Outlines are in
 * font units (1000 per em, y up); boxes, anchors and engraving defaults are
 * in staff spaces, y up, as SMuFL defines them.
 */
import type {{ GlyphData }} from './glyph'

export const unitsPerEm = 1000
export const staffSpacesPerEm = 4

export const engravingDefaults = {{
{engraving}
}} as const

export const leipzig = {{
{chr(10).join(entries)}
}} as const satisfies Record<string, GlyphData>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('verovio', type=Path, help='a Verovio checkout')
    parser.add_argument('--out', type=Path, default=Path(__file__).parents[2] / 'src' / 'renderer' / 'leipzig.ts')
    args = parser.parse_args()
    args.out.write_text(module(args.verovio), encoding='utf-8')
    print(f'wrote {len(GLYPHS)} glyphs to {args.out}')


if __name__ == '__main__':
    main()
